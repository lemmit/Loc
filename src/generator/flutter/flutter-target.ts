// The Flutter WalkerTarget — Dart/Flutter seam implementations consumed by the
// shared `walkBody` engine.  Flutter is structurally a Feliz clone: a non-JSX,
// function-call-tree target (`Column(children: [ … ])` ≈ Feliz's
// `Html.div [ prop.children [ … ] ]`), so it rides the shared walker core through
// this seam object rather than adding a WALKER_PRIMITIVE.  The primary model is
// `src/generator/feliz/feliz-target.ts`; only the syntax below is Dart, not F#.
//
// WALKING-SKELETON SCOPE (this file): the read/display path — List / Detail
// pages.  Every REQUIRED seam emits real Dart; the expression leaves forward to
// `DART_LEAVES` (`./dart-expr.ts`).  State follows the Riverpod convention: reads
// dereference the projected state record (`state.<field>`), writes call the
// Notifier's generated `set<Field>` method (`notifier.set<Field>(…)`) — emitted
// per state cell by `riverpod-emit.ts`, so the top-level write resolves (a nested
// `a.b.c := v` write still carries a TODO in `renderNestedStateWrite`).  The
// standalone controlled inputs (Field / MultilineField / PasswordField / Toggle /
// SelectField) write through the same setters, bound as a page-shell tear-off.
//
// FORMS (Track B): the three whole-primitive form overrides ship —
// `renderCreateForm` / `renderOperationForm` / `renderDestroyForm` each emit a
// reference to a self-contained `StatefulWidget` (generated by `forms-emit.ts`
// into `lib/forms.dart`) that POSTs/DELETEs over package:http and pops on
// success.  `renderAction` (one-click op button), `renderModal` (a trigger
// button that opens an op-form `AlertDialog`), and `renderWorkflowForm` (a
// `WorkflowForm(runs:)` posting to `/workflows/<wf>`) also ship.  Still DEFERRED
// success.  `renderUserComponent` ships too (a `Foo(...)` call → a Dart widget
// constructor; the component widget is emitted by `component-emit.ts`).
//
// The interactive-table seams (sort header / pager / client filter) and the
// store seams (`renderStoreFieldRead` / `renderStoreActionCall`, over the
// Riverpod store modules `store-builder.ts` emits) now ship too.  What a store
// still does NOT carry here is the lifetime ladder — `persist: local|session|url`
// emits an in-memory store under a visible TODO in `lib/stores.dart`.

